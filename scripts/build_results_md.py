def collapse_row(label, run, sub='sparsified', log='sparsification_log.csv'):
    df, src = load(run, sub, log)
    if df is None:
        add(f'| {label} | {run} | NOT RUN | | | |')
        return
    acc = df['val_acc'].values
    sp = df['sparsity'].values * 100
    a85 = np.where(acc >= 0.85)[0]
    a50 = np.where(acc >= 0.50)[0]
    s85 = f'{sp[a85[-1]]:.2f}' if len(a85) else 'n/a'
    s50 = f'{sp[a50[-1]]:.2f}' if len(a50) else 'n/a'
    coll = None
    for i in range(len(acc)):
        if acc[i] < 0.5 and acc[i:].mean() < 0.5:
            coll = i
            break
    cstep = int(df['step'].values[coll]) if coll is not None else None
    csp = f'{sp[coll]:.2f}' if coll is not None else '—'
    add(f'| {label} | `{src}` ({len(df)} rows) | {s85} | {s50} '
        f'| {cstep if cstep is not None else "never in logged range"} | {csp} |')


