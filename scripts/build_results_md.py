def load(run, sub='sparsified', log='sparsification_log.csv'):
    p = os.path.join(REPO, 'artifacts', run, sub, log)
    return (pd.read_csv(p), os.path.relpath(p, REPO)) if os.path.exists(p) else (None, None)


def fin(df):
    """Final-row stats: (dense_acc, final_acc, sparsity%, d_W, d_manifold, steps)."""
    last = df.iloc[-1]
    return (df.iloc[0]['val_acc'], last['val_acc'], last['sparsity'] * 100,
            last['d_W'], last['d_manifold'], len(df))


def wall_h(df):
    cols = [c for c in ('prune_time_s', 'adjust_time_s') if c in df.columns]
    return df[cols].sum().sum() / 3600


